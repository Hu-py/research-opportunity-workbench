"""Database-only research portrait source, without chat or manually seeded drafts.

Evidence comes ONLY from connected PostgreSQL:
  profiles, team_achievements (verified), cusp_datasets (metadata only),
  paper_discovery_candidates (human approved), papers, research_line_relations.
The source manifest is generated by program queries, never by an LLM.
"""
