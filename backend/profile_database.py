def safe_official(raw):
    """Project official profile text but NEVER embedded datasets or personal notes."""
    if not isinstance(raw,dict):return None
    team=raw.get("team") or {}
    if not isinstance(team,dict):team={}
    values=[]
    for x in raw.get("research_lines",[])[:12]:
        if not isinstance(x,dict):continue
        values.append({
            "id":str(x.get("id",""))[:90],"name":str(x.get("name",""))[:160],
            "problem":str(x.get("problem",""))[:650],
            "keywords":[str(v)[:90] for v in x.get("keywords",[])[:18]],
            "search_queries":[str(v)[:140] for v in x.get("search_queries",[])[:5]],
            "method_queries":[str(v)[:140] for v in x.get("method_queries",[])[:5]],
        })
    return {"goals":str(raw.get("goals",""))[:650],
        "team":{"name":str(team.get("name",""))[:150],
            "mission":str(team.get("mission",""))[:600],
            "priorities":[str(x)[:120] for x in team.get("priorities",[])[:10]]},
        "methods":[str(x)[:100] for x in raw.get("methods",[])[:24]],
        "research_lines":values}

def evidence_inventory(db):
    """Snapshot with stable database IDs and no sensitive asset names/paths."""
    profile=safe_official(get_profile(db))
    achieved=db.scalars(select(TeamAchievement).where(
        TeamAchievement.status=="verified").order_by(
        TeamAchievement.year.desc(),TeamAchievement.title).limit(120)).all()
    assets=db.scalars(select(CuspDataset).order_by(
        CuspDataset.category,CuspDataset.name).limit(2000)).all()
    safe_assets=[x for x in assets if x.sensitivity in ("public","internal")
                 and sensitive_level(x.name)!="restricted"]
    reviewed=db.scalars(select(PaperCandidate).where(
        PaperCandidate.status.in_(["relevant","method"])
    ).order_by(PaperCandidate.score.desc()).limit(100)).all()
    # Include only reviewed bibliography papers, not unverified scrape results.
    seen=set();papers=[]
    for candidate in reviewed:
        paper=db.get(Paper,candidate.paper_id)
        if paper and paper.id not in seen:
            seen.add(paper.id)
            papers.append({"ref":"papers:"+paper.id,"id":paper.id,
                "title":paper.title[:250],"published":paper.published,
                "doi":paper.doi[:150],"venue":paper.venue[:120],
                "line_id":candidate.line_id,"review_status":candidate.status})
    output=[{"ref":"team_achievements:"+x.id,"id":x.id,
        "title":x.title[:260],"year":x.year,"kind":x.kind,
        "tags":_safe_tags(x.tags_json)} for x in achieved]
    dataset=[{"ref":"cusp_datasets:"+x.id,"id":x.id,"name":x.name[:160],
        "category":x.category[:80],"coverage":x.coverage[:110],
        "period":x.period[:100],"format":x.format[:60]}
        for x in safe_assets]
    relations=db.scalars(select(ResearchLineRelation).where(
        ResearchLineRelation.status=="confirmed")).all()
    allowed=set(x["ref"] for x in dataset+output+papers)
    links=[{"line_id":x.line_id,"ref":("cusp_datasets:" if x.kind=="dataset"
        else "team_achievements:")+x.reference_id}
        for x in relations]
    links=[x for x in links if x["ref"] in allowed]
    return {
        "evidence_source":"postgresql_only",
        "profile":profile,
        "team_achievements":output,
        "datasets":dataset,
        "approved_papers":papers,
        "confirmed_relations":links,
        "counts":{"achievements_verified":len(achieved),
            "data_assets_total":len(assets),
            "data_assets_eligible":len(dataset),
            "data_assets_restricted_or_unclassified":len(assets)-len(dataset),
            "approved_papers":len(papers),
            "official_lines":len((profile or {}).get("research_lines",[])),
            "confirmed_links":len(links)},
        "dataset_categories":dict(Counter(x.category for x in assets)),
        "note":"数据资产仅有属性；成果 verified 表示工作台既有人工核验标记，不代表再次外部核实；官方画像也是数据库记录，不自动等于已完成成果。"
    }

def _safe_tags(raw):
    import json
    try:xs=json.loads(raw or "[]")
    except (ValueError,TypeError):xs=[]
    return [str(x)[:70] for x in xs[:12] if isinstance(x,str)] if isinstance(xs,list) else []

def matched_evidence(inventory,line):
    """Only expose human-confirmed links and explicitly line-approved papers."""
    keys={x["ref"] for x in inventory["confirmed_relations"]
          if x["line_id"]==line["id"]}
    matches=[]
    for source,rows in (("dataset",inventory["datasets"]),
                        ("achievement",inventory["team_achievements"]),
                        ("paper",inventory["approved_papers"])):
        for row in rows:
            confirmed=row["ref"] in keys
            approved_paper=source=="paper" and row.get("line_id")==line["id"]
            if not confirmed and not approved_paper:
                continue
            matches.append({"ref":row["ref"],"score":100,"category":source,
                "label":row.get("title") or row.get("name"),
                "relation":"confirmed" if confirmed else "human_approved"})
    return matches

