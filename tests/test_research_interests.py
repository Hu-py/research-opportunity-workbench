"""Offline checks for LLM-planned user research interests; no fixed-query ingestion."""
from fastapi.testclient import TestClient
from research_workbench.core import get_profile, set_profile, session_factory
import backend.api as api
import backend.interests as interests

PROFILE = {
    "research_lines":[{
        "id":"trusted","name":"Verified research line","problem":"Grounded research question",
        "keywords":["urban","graph"],"search_queries":[],"method_queries":[],
    }],"excluded_terms":[],"datasets":[],"methods":[],
}
HEADERS={"Authorization":"Bearer dev-test-api-token"}

def payload(queries=None):
    return {"title":"Graph foundation models","focus":"cs_frontier",
            "problem":"Understand how graph foundation models can support urban computing research",
            "keywords":["graph","representation"],"queries":queries or [],
            "venues":["NeurIPS","ICLR"],"enabled":True}


def test_interest_is_separate_and_search_queries_are_optional(tmp_path):
    factory=session_factory("sqlite:///"+str(tmp_path/"watchlist.db"))
    with factory() as db:
        set_profile(db,PROFILE)
        row=interests.create_interest(db,payload(),actor="test")
        interest_id=row["id"]
        assert row["queries"]==[]
        assert all(line["id"]!="interest:"+interest_id for line in get_profile(db)["research_lines"])
        assert interests.recent_papers(db,interest_id)==[]
        stored=db.get(interests.ResearchInterest,interest_id)
        assert stored.enabled is True and stored.focus=="cs_frontier"


def test_interest_api_create_list_toggle_and_scan_auth(tmp_path,monkeypatch):
    monkeypatch.setenv("API_BEARER_TOKEN","dev-test-api-token")
    monkeypatch.setenv("APP_ENV","development")
    monkeypatch.setenv("TEAM_AUTH_ENABLED","false")
    factory=session_factory("sqlite:///"+str(tmp_path/"api.db"))
    monkeypatch.setattr(api,"get_factory",lambda:factory)
    client=TestClient(api.app)
    assert client.get("/api/research-interests").status_code==401
    invalid=client.post("/api/research-interests",headers=HEADERS,json={**payload(),"title":"x"})
    assert invalid.status_code==422
    created=client.post("/api/research-interests",headers=HEADERS,json=payload())
    assert created.status_code==201,created.text
    item=created.json()
    assert item["focus"]=="cs_frontier" and item["queries"]==[]
    out=client.get("/api/research-interests",headers=HEADERS)
    assert out.status_code==200 and out.json()["items"][0]["title"]==item["title"]
    paused=client.patch("/api/research-interests/"+item["id"],headers=HEADERS,json={"enabled":False})
    assert paused.status_code==200 and paused.json()["enabled"] is False
    no_scan=client.post("/api/research-interests/"+item["id"]+"/scan",headers=HEADERS,json={})
    assert no_scan.status_code==409
    resumed=client.patch("/api/research-interests/"+item["id"],headers=HEADERS,json={"enabled":True})
    assert resumed.status_code==200
    no_key=client.post("/api/research-interests/"+item["id"]+"/scan",headers=HEADERS,json={})
    assert no_key.status_code==409


def test_interest_hints_are_not_required_or_treated_as_authoritative(tmp_path):
    factory=session_factory("sqlite:///"+str(tmp_path/"interest-hints.db"))
    with factory() as db:
        row=interests.create_interest(db,payload(["graph neural networks"]),actor="test")
        assert row["queries"]==["graph neural networks"]
        assert row["venues"]==["NeurIPS","ICLR"]
        assert row["last_status"]=="never"
        # The stored expressions are hints only; the old rule-based ingester
        # has been removed and actual queries are generated by the LLM skill.
        assert not hasattr(interests,"ingest_interests")
